-- Automatically create the default list and its 22 foods for every new user.
CREATE FUNCTION public.create_default_food_list()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    new_list_id bigint;
BEGIN
    INSERT INTO public.food_lists (owner_id, name, is_default)
    VALUES (NEW.id, 'I miei cibi', true)
    RETURNING id INTO new_list_id;

    INSERT INTO public.foods (list_id, name)
    SELECT new_list_id, name
    FROM public.default_foods
    ORDER BY id;

    RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.create_default_food_list() FROM PUBLIC;

CREATE TRIGGER create_food_list_after_signup
AFTER INSERT ON auth.users
FOR EACH ROW
EXECUTE FUNCTION public.create_default_food_list();

-- Remove the old policies that allowed every authenticated user
-- to access the same global foods.
DROP POLICY IF EXISTS "Authenticated users can add foods"
    ON public.foods;

DROP POLICY IF EXISTS "Authenticated users can delete foods"
    ON public.foods;

DROP POLICY IF EXISTS "Authenticated users can read foods"
    ON public.foods;

ALTER TABLE public.default_foods ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.food_lists ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.foods ENABLE ROW LEVEL SECURITY;

-- Users may read the template but cannot modify it.
CREATE POLICY "Authenticated users can read default foods"
ON public.default_foods
FOR SELECT
TO authenticated
USING (true);

-- Users can access only lists that they own.
CREATE POLICY "Users can read own food lists"
ON public.food_lists
FOR SELECT
TO authenticated
USING (owner_id = auth.uid());

CREATE POLICY "Users can create own food lists"
ON public.food_lists
FOR INSERT
TO authenticated
WITH CHECK (
    owner_id = auth.uid()
    AND is_default = false
);

CREATE POLICY "Users can rename own food lists"
ON public.food_lists
FOR UPDATE
TO authenticated
USING (owner_id = auth.uid())
WITH CHECK (owner_id = auth.uid());

CREATE POLICY "Users can delete own non-default food lists"
ON public.food_lists
FOR DELETE
TO authenticated
USING (
    owner_id = auth.uid()
    AND is_default = false
);

-- Foods are accessible only through a list owned by the user.
CREATE POLICY "Users can read foods in own lists"
ON public.foods
FOR SELECT
TO authenticated
USING (
    EXISTS (
        SELECT 1
        FROM public.food_lists
        WHERE food_lists.id = foods.list_id
          AND food_lists.owner_id = auth.uid()
    )
);

CREATE POLICY "Users can add foods to own lists"
ON public.foods
FOR INSERT
TO authenticated
WITH CHECK (
    EXISTS (
        SELECT 1
        FROM public.food_lists
        WHERE food_lists.id = foods.list_id
          AND food_lists.owner_id = auth.uid()
    )
);

CREATE POLICY "Users can update foods in own lists"
ON public.foods
FOR UPDATE
TO authenticated
USING (
    EXISTS (
        SELECT 1
        FROM public.food_lists
        WHERE food_lists.id = foods.list_id
          AND food_lists.owner_id = auth.uid()
    )
)
WITH CHECK (
    EXISTS (
        SELECT 1
        FROM public.food_lists
        WHERE food_lists.id = foods.list_id
          AND food_lists.owner_id = auth.uid()
    )
);

CREATE POLICY "Users can delete foods in own lists"
ON public.foods
FOR DELETE
TO authenticated
USING (
    EXISTS (
        SELECT 1
        FROM public.food_lists
        WHERE food_lists.id = foods.list_id
          AND food_lists.owner_id = auth.uid()
    )
);

