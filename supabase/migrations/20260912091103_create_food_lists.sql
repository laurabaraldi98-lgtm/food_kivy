-- Each user can own multiple food lists.
CREATE TABLE public.food_lists (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    name text NOT NULL CHECK (btrim(name) <> ''),
    is_default boolean NOT NULL DEFAULT false,
    created_at timestamp with time zone NOT NULL DEFAULT now()
);

-- A user can have only one automatically created default list.
CREATE UNIQUE INDEX food_lists_one_default_per_user
    ON public.food_lists (owner_id)
    WHERE is_default;

